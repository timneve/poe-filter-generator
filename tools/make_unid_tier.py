"""Make rules/modules/unid_tier.filter: FilterBlade's PoE2 "High Unidentified Mod Tier" grid
([0800] in rules/modules_poe2/id_mods.filter) for PoE1 (3.28 added UnidentifiedItemTier).

Same keys / cells / styles as PoE2 (ut->rare.gear4a ... ut->magic.anyremaining4j):
  gear / j(ewellery) x tier >= 4 / 3 / 2 x base rank a / b / c, then any-remaining tier >= 5 / 4.
PoE1 base ranks = NeverSink's PoE1 rare base tiers (rules/modules/rares.filter):
  gear a / b / c = rr.t1 / rr.t2 / rr.t3, jewellery a / b / c = rr->amuring.tN + rr->belts.tN.
AreaLevel >= 68 (PoE1 maps) instead of PoE2's 65. Missing keys are added to modules.toml
[unid_tier.blocks] with PoE2's default (on). Rerun after a rares.filter refresh; when NeverSink's
PoE1 export gets its own [0800] grid, import that with tools/import_neversink.py instead.

    python tools/make_unid_tier.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import build_filter as bf  # noqa: E402

OUT = ROOT / "rules" / "modules" / "unid_tier.filter"
KEY = re.compile(r"ut->(rare|magic)\.(gear|j)(\d)([abc])$")
ANY = re.compile(r"ut->(rare|magic)\.anyremaining(\d)(gear|j)$")
RANK = {"a": "t1", "b": "t2", "c": "t3"}
AREA = "AreaLevel >= 68"


def names(cond):
    return re.findall(r'"([^"]+)"', cond)


def poe1_ranks():
    """{("gear" | "j", "a" | "b" | "c"): [bases]} from our PoE1 rares module."""
    blocks = {b["key"]: b for b in bf.load_module("rares")}
    bases = lambda key: next(names(c) for c in blocks[key]["conds"] if c.startswith("BaseType"))
    out = {}
    for rank, t in RANK.items():
        out[("gear", rank)] = sorted(bases(f"rr.{t}"))
        out[("j", rank)] = sorted(bases(f"rr->amuring.{t}") + bases(f"rr->belts.{t}"))
    return out


def make():
    ranks = poe1_ranks()
    gear = bf.RARE_GROUPS["weapons"] + bf.RARE_GROUPS["armour"]
    classes = {"gear": gear, "j": bf.RARE_GROUPS["jewellery"]}
    poe2 = [b for b in bf.load_module("id_mods", ROOT / "rules" / "modules_poe2") if b["section"] == "0800"]
    if not poe2:
        raise SystemExit("no [0800] ut-> blocks in rules/modules_poe2/id_mods.filter")
    lines = ["# Generated by tools/make_unid_tier.py: FilterBlade's PoE2 [0800] unidentified-tier grid",
             "# with PoE1 base ranks (rules/modules/rares.filter rr t1 / t2 / t3). Rerun, don't edit.",
             "# Block header \"Show # <key>\": key toggled in modules.toml [unid_tier.blocks].", "",
             "# [0800] High Unidentified Mod Tier", ""]
    for b in poe2:
        m, a = KEY.match(b["key"]), ANY.match(b["key"])
        if not (m or a):
            raise SystemExit(f"unexpected PoE2 ut key {b['key']}")
        group = m.group(2) if m else a.group(3)
        conds = []
        for c in b["conds"]:
            if c.startswith("AreaLevel"):
                conds.append(AREA)
            elif c.startswith("BaseType"):
                conds.append(f"Class == {bf.q(classes[group])}")
                conds.append(f"BaseType == {bf.q(ranks[(group, m.group(4))])}")
            elif c.startswith("Class"):
                conds.append(f"Class == {bf.q(classes[group])}")
            else:
                conds.append(c)
        lines.append(" ".join([f"{b['action']} # {b['key']}"] + b["tags"]))
        lines += [f"\t{c}" for c in conds + b["style"]] + [""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    return [b["key"] for b in poe2]


def add_toggles(keys, path=ROOT / "modules.toml"):
    """Append missing keys to [unid_tier.blocks] (PoE2 default: on)."""
    text = path.read_text(encoding="utf-8")
    if "[unid_tier.blocks]" not in text:
        text = text.rstrip("\n") + "\n\n[unid_tier.blocks]\n"
    have = set(re.findall(r'^"([^"]+)" =', text.split("[unid_tier.blocks]", 1)[1], re.M))
    new = "".join(f'"{k}" = true  # [0800] Show\n' for k in keys if k not in have)
    head, tail = text.split("[unid_tier.blocks]\n", 1)
    nxt = re.search(r"^\[", tail, re.M)
    cut = nxt.start() if nxt else len(tail)
    tail = tail[:cut].rstrip("\n") + ("\n" if tail[:cut].strip() else "") + new + ("\n" + tail[cut:] if nxt else "")
    path.write_text(head + "[unid_tier.blocks]\n" + tail, encoding="utf-8")


if __name__ == "__main__":
    keys = make()
    add_toggles(keys, Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "modules.toml")
    print(f"{OUT.relative_to(ROOT)}: {len(keys)} blocks")
