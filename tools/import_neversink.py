"""Make / refresh one of our rule modules from a NeverSink (FilterBlade) export.

    python tools/import_neversink.py <module> <first>:<after> [<first>:<after> ...] [--ref FILE]
    python tools/import_neversink.py --game poe2 <module> <first>:<after> ...

Copies the blocks of sections [first, after) ("after" = end: to the end of the file) of
reference/league.filter (default) into rules/modules/<module>.filter (our own file from then
on: the build never reads reference/ for it) and writes the [<module>.blocks] table of
modules.toml: one key per block ("type.tier" from
NeverSink's tag), default = on / off as in the export (commented-out "#Show" = off). On a
refresh, keys already in modules.toml keep their value; new keys get the export's default.
Borders / backgrounds are dropped (calm look), beams made permanent (no Temp). Run it again when a league adds mods / bases.
--game poe2: reference/league-filterblade-poe2.filter -> rules/modules_poe2/ + modules_poe2.toml;
tink blocks (white background) keep their border / background there (PoE2 build: no_borders).
--config-key REGEX=NOTE: keys matching REGEX get the string value NOTE instead of true/false
(blocks an emitter decides from config.toml, e.g. rares: --config-key "rr(->\\w+)?\\.t\\d=config.toml [rares]").
"""
import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import build_filter as bf  # noqa: E402

# --game -> (default reference export, module dir, toggle file, keep tink border / background)
GAMES = {"poe1": ("reference/league.filter", "rules/modules", "modules.toml", False),
         "poe2": ("reference/league-filterblade-poe2.filter", "rules/modules_poe2", "modules_poe2.toml", True)}
MODULES_TOML = ROOT / "modules.toml"
TINK_BACKGROUND = "SetBackgroundColor 255 255 255 255"
HEADER = """# Generated by tools/import_neversink.py from {ref}, then ours: edit freely.
# Block header "Show # <key>": key toggled in {toml} [{name}.blocks]. Section lines
# "# [NNNN] title" keep NeverSink's numbering (emitters select by them).
"""
# NeverSink strictness tags kept after the key (block header "Show # <key> %D3"): %D<n> = off at
# FilterBlade strictness >= n, %H<n> = Hide at >= n, !utility_layer = optional hide layer
# (load_module "tags"; emit_leveling decides those blocks from config.toml [leveling] strictness)
NS_TAG = re.compile(r"%[DH]\d|!utility_layer\b")


def section_heads(lines):
    """NeverSink section number -> line index (last match: the first ones are the TOC)."""
    heads = {}
    for i, l in enumerate(lines):
        m = re.match(r"#\s+\[\[?(\d{4})\]\]?", l)
        if m:
            heads[m.group(1)] = i
    return heads


def parse_ref_blocks(ref_text, first, after, keep_tink=False):
    """Blocks of a NeverSink export's sections [first, after): [{action, comment, key, section,
    off, conds, style}]. off = commented-out "#Show" block (FilterBlade rule turned off).
    key = "type.tier" from NeverSink's "$type->X $tier->Y" tag (untagged: "s<section>_<n>").
    Commented-out "#Hide" blocks are parsed too (off; league start never turns them on).
    style drops SetBorderColor / SetBackgroundColor (calm look; keep_tink: not on white-background
    tink blocks) and PlayEffect Temp (permanent beams). after = "end": to the end of the file."""
    lines = ref_text.splitlines()
    heads = section_heads(lines)
    if after == "end":
        heads["end"] = len(lines)
    if first not in heads or after not in heads:
        raise ValueError(f"section [{first}] or [{after}] not found in reference filter")
    i, end, section, untagged, out = heads[first], heads[after], first, {}, []
    while i < end:
        h = re.match(r"#\s+\[\[?(\d{4})\]\]?", lines[i])
        if h:
            section = h.group(1)
        m = re.match(r"(Show|Hide)\b\s*#?\s*(.*)$", lines[i])
        commented = False
        if not m:
            m = re.match(r"#(Show|Hide)\b\s*#?\s*#?\s*(.*)$", lines[i])
            commented = bool(m)
        i += 1
        if not m:
            continue
        body = []
        while i < end and lines[i].strip() and not re.match(r"#?(Show|Hide|Minimal)\b", lines[i]):
            line = lines[i]
            if line.startswith("#"):
                line = line[1:]
                if not commented or not line.strip() or line.lstrip()[0] in "#-=":
                    break
            body.append(line.strip())
            i += 1
        tag = re.search(r"\$type->(\S+)\s+\$tier->(\S+)", m.group(2))
        if tag:
            key = f"{tag.group(1)}.{tag.group(2)}"
        else:
            untagged[section] = untagged.get(section, 0) + 1
            key = f"s{section}_{untagged[section]}"
        tink = keep_tink and TINK_BACKGROUND in body
        out.append({"action": m.group(1), "comment": m.group(2), "key": key, "section": section,
                    "off": commented,
                    "conds": [l for l in body if not bf.STYLE_RE.match(l)],
                    "style": [re.sub(r"^(PlayEffect \w+) Temp$", r"\1", l) for l in body if bf.STYLE_RE.match(l)
                              and (tink or not l.startswith(("SetBorderColor", "SetBackgroundColor")))]})
    return out


def section_span(ref_text):
    """(first section, "end"): every block of an export."""
    heads = section_heads(ref_text.splitlines())
    return min(heads, key=heads.get), "end"


def section_titles(ref_text):
    titles = {}
    for line in ref_text.splitlines():
        m = re.match(r"#\s+\[\[?(\d{4})\]\]?\s*(.*)$", line)
        if m:
            titles[m.group(1)] = m.group(2).strip()
    return titles


def module_text(name, blocks, titles, ref="reference/league.filter", toml="modules.toml"):
    out, section = HEADER.format(name=name, ref=ref, toml=toml), None
    for b in blocks:
        if b["section"] != section:
            section = b["section"]
            out += f"\n# [{section}] {titles.get(section, '')}\n"
        tags = "".join(f" {t}" for t in NS_TAG.findall(b["comment"]))
        out += f"\n{b['action']} # {b['key']}{tags}\n" + "".join(f"\t{l}\n" for l in b["conds"] + b["style"])
    return out


def stock_note(b, stock):
    """" (stock NeverSink: ...)" when the unedited export (--stock) differs from b, else ""."""
    if stock is None:
        return ""
    s = stock.get(b["key"])
    if s is None:
        return " (not in stock NeverSink)"
    if (s["action"], s["off"]) == (b["action"], b["off"]):
        return ""
    return f" (stock NeverSink: {'off' if s['off'] else s['action']})"


def toml_table(name, blocks, old, config_keys=(), stock=None):
    """config_keys: [(regex, note)]: keys fully matching regex get the string value note (block
    decided by an emitter's config.toml options, not by this toggle). stock: key -> block of the
    unedited NeverSink export (--stock): the comment says where the user's export differs."""
    lines = [f"[{name}.blocks]"]
    for b in blocks:
        note = next((n for rx, n in config_keys if re.fullmatch(rx, b["key"])), None)
        val = note if note is not None else old.get(b["key"], not b["off"])
        val = '"' + val + '"' if isinstance(val, str) else "true" if val else "false"
        lines.append(f'"{b["key"]}" = {val}  # [{b["section"]}] {b["action"]}'
                     + (" (off in FilterBlade)" if b["off"] else "") + stock_note(b, stock))
    return "\n".join(lines) + "\n"


def write_toml_table(name, table, path=None):
    path = path or MODULES_TOML
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    pat = re.compile(rf"^\[{re.escape(name)}\.blocks\]\n(?:(?!\[).*\n?)*", re.M)
    text = pat.sub(lambda _: table + "\n", text, count=1) if pat.search(text) else text.rstrip("\n") + "\n\n" + table
    path.write_text(text.lstrip("\n"), encoding="utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("module")
    ap.add_argument("ranges", nargs="+", help="first:after section numbers, e.g. 0600:0803")
    ap.add_argument("--game", choices=GAMES, default="poe1")
    ap.add_argument("--ref", help="NeverSink export (default: the --game one)")
    ap.add_argument("--stock", help="unedited NeverSink export of the same strictness: modules.toml "
                                    "comments note blocks the user changed (e.g. reference/regular-neversink-poe2.filter)")
    ap.add_argument("--config-key", action="append", default=[], metavar="REGEX=NOTE",
                    help='keys matching REGEX are set by config.toml, value "NOTE" (e.g. rares rr tiers)')
    a = ap.parse_args(argv)
    config_keys = [tuple(c.split("=", 1)) for c in a.config_key]
    ref_rel, mod_rel, toml_rel, keep_tink = GAMES[a.game]
    ref = Path(a.ref) if a.ref else ROOT / ref_rel
    mod_dir, toml_path = ROOT / mod_rel, ROOT / toml_rel
    ref_text = ref.read_text(encoding="utf-8")
    blocks = [b for r in a.ranges for b in parse_ref_blocks(ref_text, *r.split(":"), keep_tink=keep_tink)]
    keys = [b["key"] for b in blocks]
    dup = {k for k in keys if keys.count(k) > 1}
    if dup:
        raise SystemExit(f"duplicate block keys: {sorted(dup)}")
    mod_dir.mkdir(parents=True, exist_ok=True)
    (mod_dir / f"{a.module}.filter").write_text(
        module_text(a.module, blocks, section_titles(ref_text), f"reference/{ref.name}", toml_rel), encoding="utf-8")
    old = tomllib.loads(toml_path.read_text(encoding="utf-8")).get(a.module, {}).get("blocks", {}) \
        if toml_path.exists() else {}
    stock = None
    if a.stock:
        stock_text = Path(a.stock).read_text(encoding="utf-8")
        stock = {b["key"]: b for b in parse_ref_blocks(stock_text, *section_span(stock_text))}
    write_toml_table(a.module, toml_table(a.module, blocks, old, config_keys, stock), toml_path)
    print(f"{a.module}: {len(blocks)} blocks ({sum(b['off'] for b in blocks)} off) -> "
          f"{mod_rel}/{a.module}.filter + {toml_rel} [{a.module}.blocks]")


if __name__ == "__main__":
    main()
