"""Make / refresh fallback_tiers.toml: NeverSink's tier group per currency / card name, used
by the build only when poe.ninja has no confident price (league start, thin cards).

    python tools/import_fallback_tiers.py [--ref FILE] [--cards FILE]

Currency, corpses, vials: NeverSink tier number (t1 best .. t9) from reference/league.filter.
Divination cards: NeverSink card group (t1, t2, t3, tnew, t4c, t4, t5c, t5) from
reference/regular-neversink.filter (stock NeverSink: the user's league.filter has hand-moved
cards). Stack-size blocks skipped; first (best) group wins; only groups that config.toml
[exchange.reference_currency_tiers] / [exchange.reference_card_tiers] map. The build never
reads reference/ for this: it reads fallback_tiers.toml (our file from then on; run this
again when a league adds currency / cards).
"""
import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "fallback_tiers.toml"
HEADER = """# Generated by tools/import_fallback_tiers.py (from NeverSink: currency / corpses / vials =
# reference/league.filter tier number, cards = reference/regular-neversink.filter group), then ours.
# Used ONLY for items poe.ninja has no confident price for (config.toml [exchange]
# unpriced_currency = "reference", card_fallback_min_volume). Our tier per group:
# config.toml [exchange.reference_currency_tiers] / [exchange.reference_card_tiers].
# Every known name is listed; edit a value to move one item, or rerun the tool.
"""


def parse_currency(cfg, text):
    """currency name -> NeverSink tier number ("1".."9"), currency / corpses / vials blocks."""
    mapping = cfg["exchange"].get("reference_currency_tiers", {})
    out = {}
    for blk in re.split(r"\n(?=(?:Show|Hide|Minimal)\b)", text):
        m = re.search(r"\$type->(?:currency|corpses|vials)\S* \$tier->t(\d+)", blk.split("\n", 1)[0])
        if not m or m.group(1) not in mapping or re.search(r"^\s*StackSize", blk, re.M):
            continue
        for conds in re.findall(r"^\s*BaseType == (.*)$", blk, re.M):
            for name in re.findall(r'"([^"]+)"', conds):
                out.setdefault(name, m.group(1))
    return out


def parse_cards(cfg, text):
    """card name -> NeverSink divination group ("t1", "t4c", ...)."""
    mapping = cfg["exchange"]["reference_card_tiers"]
    out = {}
    for blk in re.split(r"\n(?=(?:Show|Hide|Minimal)\b)", text):
        m = re.search(r"\$type->divination \$tier->(\S+)", blk.split("\n", 1)[0])
        if not m or m.group(1) not in mapping or re.search(r"^\s*StackSize\b", blk, re.M):
            continue
        for conds in re.findall(r"^\s*BaseType ==? (.*)$", blk, re.M):
            for name in re.findall(r'"([^"]+)"', conds):
                out.setdefault(name, m.group(1))
    return out


def toml_text(currency, cards, group_order):
    def table(name, entries, order):
        lines = [f"[{name}]"]
        for group in order:
            names = sorted(n for n, g in entries.items() if g == group)
            if names:
                lines.append(f"# {group}")
                lines += [f'"{n}" = "{group}"' for n in names]
        return "\n".join(lines) + "\n"
    cur_order = sorted(set(currency.values()), key=int)
    card_order = [g for g in group_order if g in set(cards.values())]
    return HEADER + "\n" + table("currency", currency, cur_order) + "\n" + table("cards", cards, card_order)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", default=str(ROOT / "reference/league.filter"))
    ap.add_argument("--cards", default=str(ROOT / "reference/regular-neversink.filter"))
    a = ap.parse_args(argv)
    cfg = tomllib.loads((ROOT / "config.toml").read_text(encoding="utf-8"))  # mappings only
    currency = parse_currency(cfg, Path(a.ref).read_text(encoding="utf-8"))
    cards = parse_cards(cfg, Path(a.cards).read_text(encoding="utf-8"))
    OUT.write_text(toml_text(currency, cards, list(cfg["exchange"]["reference_card_tiers"])), encoding="utf-8")
    print(f"fallback_tiers.toml: {len(currency)} currency, {len(cards)} cards")


if __name__ == "__main__":
    main()
